const meta = (key: string, value: string) => `<wp:postmeta><wp:meta_key><![CDATA[${key}]]></wp:meta_key><wp:meta_value><![CDATA[${value}]]></wp:meta_value></wp:postmeta>`;

function exportItem(id: number, type: string, status: string, title: string, body = ''): string {
  return `<item><title><![CDATA[${title}]]></title><wp:post_id>${id}</wp:post_id><wp:status><![CDATA[${status}]]></wp:status><wp:post_type><![CDATA[${type}]]></wp:post_type>${body}</item>`;
}

function exportFile(items: string, site = 'https://alt.example/'): string {
  return `<?xml version="1.0" encoding="UTF-8" ?><rss version="2.0" xmlns:wp="http://wordpress.org/export/1.2/"><channel><title>Alt</title><wp:wxr_version>1.2</wp:wxr_version><wp:base_site_url>${site}</wp:base_site_url>${items}</channel></rss>`;
}

describe('reading a WordPress export', () => {
  it('takes slides with their settings and the attachment files', () => {
    const xml = exportFile([
      exportItem(7, 'foyer_slide', 'publish', 'Tag & Nacht', meta('slide_format', 'text') + meta('slide_text_title', 'Grüße ]]]]><![CDATA[> 🎉') + meta('_edit_last', '1')),
      exportItem(3, 'foyer_slide', 'draft', 'Entwurf', meta('slide_format', 'default')),
      exportItem(4, 'foyer_slide', 'trash', 'Papierkorb'),
      exportItem(5, 'post', 'publish', 'Beitrag', meta('slide_format', 'text')),
      exportItem(9, 'attachment', 'inherit', 'Bild', `<wp:attachment_url><![CDATA[https://cdn.example/files/2026/03/a.jpg]]></wp:attachment_url>${meta('_wp_attached_file', '2026/03/a.jpg')}`),
    ].join(''));

    const result = readWordPressExport(xml);

    expect(result.slides).toEqual([
      { id: 3, title: 'Entwurf', status: 'draft', meta: { slide_format: 'default' } },
      { id: 7, title: 'Tag & Nacht', status: 'publish', meta: { slide_format: 'text', slide_text_title: 'Grüße ]]> 🎉' } },
    ]);
    expect([...result.attachments]).toEqual([[9, '2026/03/a.jpg']]);
    expect(result.uploadsUrl).toBe('https://cdn.example/files');
  });

  it('does not confuse item markup inside the text with items', () => {
    const xml = exportFile(exportItem(7, 'foyer_slide', 'publish', 'Eins', meta('slide_text_content', '</item><item>')));
    expect(readWordPressExport(xml).slides).toHaveLength(1);
    expect(readWordPressExport(xml).slides[0].meta.slide_text_content).toBe('</item><item>');
  });

  it('falls back to the usual uploads folder of the site', () => {
    expect(readWordPressExport(exportFile('')).uploadsUrl).toBe('https://alt.example/wp-content/uploads');
  });

  it('refuses other files', () => {
    expect(() => readWordPressExport('<rss><channel><title>Fremd</title></channel></rss>')).toThrow('keine WordPress-Exportdatei');
    expect(() => readWordPressExport('kein XML')).toThrow();
  });
});

const hasFfmpeg = spawnSync('ffmpeg', ['-version']).status === 0 && spawnSync('ffprobe', ['-version']).status === 0;

function slide(id: number, meta: Record<string, string>, extra: Partial<WpSlide> = {}): WpSlide {
  return { id, title: `Folie ${id}`, status: 'publish', meta, ...extra };
}

function data(slides: WpSlide[], extra: Partial<WpData> = {}): WpData {
  return { slides, attachments: new Map(), zoomByDefault: false, uploadsUrl: 'https://alt.example/wp-content/uploads', ...extra };
}

/** Images generated by ffmpeg, in a folder laid out like WordPress uploads. */
function uploads() {
  const dir = mkdtempSync(join(tmpdir(), 'foyer-wp-uploads-'));
  mkdirSync(join(dir, '2026/03'), { recursive: true });
  const color = (name: string, value: string) => {
    const result = spawnSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', `color=c=${value}:s=320x180`, '-frames:v', '1', join(dir, name)]);
    if (result.status !== 0) throw new Error(result.stderr.toString());
  };
  color('2026/03/blau.jpg', 'blue');
  color('2026/03/rot.jpg', 'red');
  return dir;
}

describe('WordPress-Import: nur Textfolien', () => {
  it('keeps text slides and leaves standard slides and videos for later', () => {
    const slides = [
      slide(1, { slide_format: 'text', slide_background: 'image', slide_bg_image_image: '9', slide_text_title: 'Mit Bild' }),
      slide(2, { slide_format: 'text', slide_background: 'default', slide_text_title: 'Nur Text' }),
      slide(3, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9' }),
      slide(4, { slide_format: 'text', slide_background: 'html5-video', slide_bg_html5_video_video: '8', slide_text_title: 'Mit Video' }),
      slide(5, { slide_format: 'default', slide_background: 'html5-video', slide_bg_html5_video_video: '8' }),
    ];
    const attachments = new Map([[8, 'a.mp4'], [9, 'a.jpg']]);

    const plan = planImport(data(slides, { attachments }), { onlyText: true });

    expect(plan.slides.map((s) => s.wpId)).toEqual([1, 2]);
    expect(plan.skipped.map((s) => s.wpId)).toEqual([3, 4, 5]);
    expect(planImport(data(slides, { attachments })).slides).toHaveLength(5);
  });
});

describe('WordPress-Import: Abbildung', () => {
  it('übernimmt die Textfelder und den Zoom', () => {
    const plan = planImport(
      data(
        [
          slide(1, {
            slide_format: 'text',
            slide_background: 'image',
            slide_bg_image_image: '9',
            slide_bg_image_zoom: 'enabled',
            slide_text_pretitle: 'Dach',
            slide_text_title: 'Titel &amp; mehr',
            slide_text_subtitle: 'Unter',
            slide_text_content: 'Zeile 1\r\nZeile 2',
            slide_text_qr: 'https://example.org/x',
            slide_text_qr_ecc: 'q',
          }),
        ],
        { attachments: new Map([[9, '2026/03/blau.jpg']]) },
      ),
    );
    expect(plan.skipped).toEqual([]);
    expect(plan.slides[0]).toMatchObject({
      wpId: 1,
      type: 'text',
      published: true,
      zoom: true,
      fileAs: 'background',
      file: { attachmentId: 9, path: '2026/03/blau.jpg', kind: 'image' },
      config: { pretitle: 'Dach', title: 'Titel & mehr', subtitle: 'Unter', content: 'Zeile 1\nZeile 2', qrUrl: 'https://example.org/x', qrEcc: 'Q' },
    });
  });

  it('nimmt für „inherit“ die alte globale Zoom-Einstellung', () => {
    const meta = { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9', slide_bg_image_zoom: 'inherit' };
    const attachments = new Map([[9, 'a.jpg']]);
    expect(planImport(data([slide(1, meta)], { attachments })).slides[0].zoom).toBe(false);
    expect(planImport(data([slide(1, meta)], { attachments, zoomByDefault: true })).slides[0].zoom).toBe(true);
    const off = { ...meta, slide_bg_image_zoom: 'disabled' };
    expect(planImport(data([slide(1, off)], { attachments, zoomByDefault: true })).slides[0].zoom).toBe(false);
  });

  it('macht aus einer reinen Bildfolie eine Text-Folie ohne Text', () => {
    const plan = planImport(data([slide(1, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9' })], { attachments: new Map([[9, 'a.jpg']]) }));
    expect(plan.slides[0]).toMatchObject({ type: 'text', config: {}, fileAs: 'background' });
  });

  it('macht aus einem reinen Video eine Video-Folie, mit Text bleibt es Hintergrund', () => {
    const attachments = new Map([[5, 'v.mp4']]);
    const video = { slide_background: 'html5-video', slide_bg_html5_video_video: '5' };
    const plan = planImport(
      data([slide(1, { slide_format: 'default', ...video }), slide(2, { slide_format: 'text', slide_text_title: 'T', ...video })], { attachments }),
    );
    expect(plan.slides[0]).toMatchObject({ type: 'video', fileAs: 'video' });
    expect(plan.slides[1]).toMatchObject({ type: 'text', fileAs: 'background', file: { kind: 'video' } });
  });

  it('findet ein Video auch nur über seine Adresse', () => {
    const plan = planImport(
      data([
        slide(1, {
          slide_format: 'default',
          slide_background: 'html5-video',
          slide_bg_html5_video_video: '0',
          slide_bg_html5_video_video_url: 'https://alt.example/wp-content/uploads/2026/03/mein%20film.m4v',
        }),
      ]),
    );
    expect(plan.slides[0].file).toEqual({ attachmentId: null, path: '2026/03/mein film.m4v', kind: 'video' });
  });

  it('überspringt YouTube, andere Folientypen und leere Folien mit Begründung', () => {
    const plan = planImport(
      data([
        slide(1, { slide_format: 'default', slide_background: 'video', slide_bg_video_video_url: 'https://youtu.be/x' }),
        slide(2, { slide_format: 'text', slide_background: 'video', slide_text_title: 'T' }),
        slide(3, { slide_format: 'iframe' }),
        slide(4, { slide_format: 'webuntis-room-display' }),
        slide(5, { slide_format: 'default', slide_background: 'default' }),
        slide(6, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '0' }),
      ]),
    );
    expect(plan.slides).toEqual([]);
    expect(plan.skipped.map((s) => s.wpId)).toEqual([1, 2, 3, 4, 5, 6]);
    expect(plan.skipped[0].reason).toContain('YouTube');
    expect(plan.skipped[2].reason).toContain('Externe Webseite');
  });

  it('behält den Text, wenn das Bild fehlt, und warnt', () => {
    const plan = planImport(data([slide(1, { slide_format: 'text', slide_background: 'image', slide_bg_image_image: '0', slide_text_title: 'T' })]));
    expect(plan.slides[0].file).toBeNull();
    expect(plan.slides[0].warnings[0]).toContain('ohne Hintergrund');
  });

  it('entfernt HTML, ungültige QR-Inhalte und übernimmt Entwürfe unveröffentlicht', () => {
    const plan = planImport(
      data([
        slide(1, { slide_format: 'text', slide_text_title: 'T', slide_text_content: '<p>Eins</p><p>Zwei<br>Drei</p>', slide_text_qr: 'kein link' }, { status: 'draft', title: '' }),
      ]),
    );
    expect(plan.slides[0]).toMatchObject({ published: false, title: 'T', config: { content: 'Eins\n\nZwei\nDrei', qrUrl: '' } });
    expect(plan.slides[0].warnings).toHaveLength(2);
  });
});

