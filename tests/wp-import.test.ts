describe.runIf(hasFfmpeg)('WordPress-Import: Ablauf', () => {
  const source = () =>
    data(
      [
        slide(1, { slide_format: 'text', slide_background: 'image', slide_bg_image_image: '9', slide_bg_image_zoom: 'enabled', slide_text_title: 'Mit Bild' }),
        slide(2, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9' }),
        slide(3, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '8' }, { status: 'draft' }),
        slide(4, { slide_format: 'text', slide_background: 'image', slide_bg_image_image: '7', slide_text_title: 'Bild weg' }),
        slide(5, { slide_format: 'iframe' }),
      ],
      {
        attachments: new Map([
          [9, '2026/03/blau.jpg'],
          [8, '2026/03/rot.jpg'],
          [7, '2026/03/fehlt.jpg'],
        ]),
      },
    );
  const count = (db: Awaited<ReturnType<typeof setup>>['ctx']['db'], table: string) => (db.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get() as { n: number }).n;

  it('ändert im Trockenlauf nichts und zeigt, was passieren würde', async () => {
    const { ctx } = await setup();
    const slidesBefore = count(ctx.db, 'slides');
    const result = await runImport(ctx, planImport(source()), wpFiles(uploads()), { apply: false });
    expect(result.created.map((c) => c.wpId)).toEqual([1, 2, 3]);
    expect(result.files).toBe(2);
    expect(result.failed.map((f) => f.wpId)).toEqual([4]);
    expect(result.failed[0].error).toContain('fehlt.jpg');
    expect(result.skipped.map((s) => s.wpId)).toEqual([5]);
    expect(count(ctx.db, 'slides')).toBe(slidesBefore);
    expect(count(ctx.db, 'media')).toBe(0);
    expect(count(ctx.db, 'wp_import_map')).toBe(0);
  });

  it('kopiert jedes Bild einmal, legt Folien an und plant nichts ein', async () => {
    const { ctx } = await setup();
    const schedules = count(ctx.db, 'schedules');
    const channelSlides = count(ctx.db, 'channel_slides');
    const result = await runImport(ctx, planImport(source()), wpFiles(uploads()), { apply: true });
    expect(result.created).toHaveLength(3);
    expect(result.mediaFailed).toEqual([]);
    expect(count(ctx.db, 'media')).toBe(2);
    expect(count(ctx.db, 'schedules')).toBe(schedules);
    expect(count(ctx.db, 'channel_slides')).toBe(channelSlides);

    const row = (wpId: number) => {
      const id = result.created.find((c) => c.wpId === wpId)!.id;
      return ctx.db.prepare('SELECT * FROM slides WHERE id = ?').get(id!) as Record<string, any>;
    };
    const first = row(1);
    const background = JSON.parse(first.background_json);
    expect(first).toMatchObject({ type: 'text', title: 'Folie 1', published: 1, duration: null });
    expect(JSON.parse(first.config_json).title).toBe('Mit Bild');
    expect(background).toMatchObject({ kind: 'image', fit: 'cover', dim: 0, zoom: true });
    expect(ctx.media.get(background.mediaId)?.status).toBe('ready');
    expect(JSON.parse(row(2).background_json).mediaId).toBe(background.mediaId);
    expect(row(3).published).toBe(0);
  });

  it('übernimmt beim zweiten Lauf nur Neues und lässt geänderte Folien in Ruhe', async () => {
    const { ctx } = await setup();
    const dir = uploads();
    const first = await runImport(ctx, planImport(source()), wpFiles(dir), { apply: true });
    const edited = first.created[0].id!;
    ctx.db.prepare('UPDATE slides SET title = ? WHERE id = ?').run('In Foyer geändert', edited);
    const mediaBefore = count(ctx.db, 'media');
    const slidesBefore = count(ctx.db, 'slides');

    const again = source();
    again.slides.push(slide(6, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9' }));
    const second = await runImport(ctx, planImport(again), wpFiles(dir), { apply: true });
    expect(second.alreadyImported).toBe(3);
    expect(second.created.map((c) => c.wpId)).toEqual([6]);
    expect(second.files).toBe(0);
    expect(count(ctx.db, 'media')).toBe(mediaBefore);
    expect(count(ctx.db, 'slides')).toBe(slidesBefore + 1);
    expect((ctx.db.prepare('SELECT title FROM slides WHERE id = ?').get(edited) as { title: string }).title).toBe('In Foyer geändert');
  });

  it('holt die Dateien auch über die alte Adresse', async () => {
    const { ctx } = await setup();
    const dir = uploads();
    const requested: string[] = [];
    const realFetch = globalThis.fetch;
    globalThis.fetch = (async (input: string, init?: RequestInit) => {
      const path = new URL(input).pathname.replace('/wp-content/uploads/', '');
      requested.push(`${init?.method ?? 'GET'} ${path}`);
      try {
        return new Response(init?.method === 'HEAD' ? null : readFileSync(join(dir, path)));
      } catch {
        return new Response(null, { status: 404 });
      }
    }) as typeof fetch;
    try {
      const result = await runImport(ctx, planImport(data([slide(1, { slide_format: 'default', slide_background: 'image', slide_bg_image_image: '9' })], { attachments: new Map([[9, '2026/03/blau.jpg']]) })), wpFiles('https://alt.example/wp-content/uploads/'), { apply: true });
      expect(result.failed).toEqual([]);
      expect(result.created).toHaveLength(1);
      expect(requested).toEqual(['HEAD 2026/03/blau.jpg', 'GET 2026/03/blau.jpg']);
    } finally {
      globalThis.fetch = realFetch;
    }
  });
});
