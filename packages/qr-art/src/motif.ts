export type IconName = keyof typeof ICONS;
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

export const MAX_TEXT = 10;

export interface Grid {
  width: number;
  height: number;
  /** width*height: 1 dark, 0 light, -1 don't care. */
  cells: Int8Array;
}

export function emptyGrid(width: number, height: number, fill = -1): Grid {
  return { width, height, cells: new Int8Array(width * height).fill(fill) };
}

export function parseMotif(motif: string): Grid {
  const rows = motif.split('\n').map((r) => r.replace(/\s+$/, '')).filter((r, i, all) => r || all.slice(i).some(Boolean));
  while (rows.length && !rows[rows.length - 1]) rows.pop();
  const width = Math.max(0, ...rows.map((r) => r.length));
  const grid = emptyGrid(width, rows.length);
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) grid.cells[y * width + x] = row[x] === '#' ? 1 : row[x] === '.' ? 0 : -1;
  });
  return grid;
}

export function formatMotif(grid: Grid): string {
  const rows: string[] = [];
  for (let y = 0; y < grid.height; y++) {
    let row = '';
    for (let x = 0; x < grid.width; x++) {
      const c = grid.cells[y * grid.width + x];
      row += c === 1 ? '#' : c === 0 ? '.' : '-';
    }
    rows.push(row);
  }
  return rows.join('\n');
}

function blit(grid: Grid, rows: string[], ox: number, oy: number) {
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) grid.cells[(oy + y) * grid.width + ox + x] = row[x] === '#' ? 1 : 0;
  });
}

function glyph(ch: string): string[] {
  return (FONT[ch] ?? FONT['?']).split('|');
}

/** Text (5×7 letters) and/or an icon, icon above, with a light frame around it. */
export function composeMotif(text: string, icon: IconName | '' = ''): string {
  const chars = [...text.toUpperCase().slice(0, MAX_TEXT)];
  const textWidth = chars.length ? chars.length * 6 - 1 : 0;
  const iconRows = icon ? ICONS[icon] : null;
  if (!textWidth && !iconRows) return '';
  const contentWidth = Math.max(textWidth, iconRows ? 9 : 0);
  const contentHeight = (iconRows ? 9 : 0) + (iconRows && textWidth ? 2 : 0) + (textWidth ? 7 : 0);
  const grid = emptyGrid(contentWidth + 2, contentHeight + 2, 0);
  let y = 1;
  if (iconRows) {
    blit(grid, iconRows, 1 + Math.floor((contentWidth - 9) / 2), y);
    y += textWidth ? 11 : 9;
  }
  chars.forEach((ch, i) => blit(grid, glyph(ch), 1 + Math.floor((contentWidth - textWidth) / 2) + i * 6, y));
  return formatMotif(grid);
}
